function buildLedMatrix(container, text, opts = {}) {
  const rows = 7;
  const gap = 1; // colonne vide entre lettres
  const glyphs = text.toUpperCase().split("").map(ch => LED_FONT[ch] || LED_FONT[" "]);
  const totalCols = glyphs.reduce((sum, g) => sum + 5 + gap, 0);

  // Construit la grille de bits complète (rows x totalCols)
  const bits = Array.from({ length: rows }, () => new Array(totalCols).fill(0));
  let col = 0;
  glyphs.forEach(g => {
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < 5; c++) {
        bits[r][col + c] = g[r][c] === "1" ? 1 : 0;
      }
    }
    col += 5 + gap;
  });

  const visibleCols = opts.visibleCols || 34;
  container.innerHTML = "";
  container.classList.add("led-matrix");
  container.style.setProperty("--led-rows", rows);
  container.style.setProperty("--led-cols", visibleCols);

  const dots = [];
  for (let r = 0; r < rows; r++) {
    const rowEl = document.createElement("div");
    rowEl.className = "led-row";
    const rowDots = [];
    for (let c = 0; c < visibleCols; c++) {
      const dot = document.createElement("span");
      dot.className = "led-dot";
      rowEl.appendChild(dot);
      rowDots.push(dot);
    }
    dots.push(rowDots);
    container.appendChild(rowEl);
  }

  let offset = -visibleCols;
  const speed = opts.speedMs || 90;

  function frame() {
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < visibleCols; c++) {
        const srcCol = offset + c;
        const on = srcCol >= 0 && srcCol < totalCols && bits[r][srcCol] === 1;
        dots[r][c].classList.toggle("on", on);
      }
    }
    offset++;
    if (offset > totalCols) offset = -visibleCols;
  }

  frame();
  const timer = setInterval(frame, speed);
  return () => clearInterval(timer);
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-led-text]").forEach(el => {
    buildLedMatrix(el, el.getAttribute("data-led-text") || "ATELIER", {
      visibleCols: parseInt(el.getAttribute("data-led-cols") || "34", 10),
      speedMs: parseInt(el.getAttribute("data-led-speed") || "90", 10)
    });
  });
});
